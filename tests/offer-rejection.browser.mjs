import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { chromium } from 'playwright'
import { createWorkflowFixture, offerDraft } from './workflowFixture.js'

const env = { DEMO_ADMIN_CPF: '12345678901', DEMO_ADMIN_PASSWORD: 'teste123', DEMO_ADMIN_NAME: 'Gustavo' }
const fixture = await createWorkflowFixture({ accountsEnv: env })
const browser = await chromium.launch()
await mkdir('test-results', { recursive: true })
try {
  const online = (await fixture.adminRequest('/offers', 'POST', { ...offerDraft, service: 'Oferta do cliente' })).data.item
  await fixture.mutateStore((store) => { store.offers.find((row) => row.id === online.id).origin = 'Portal do cliente' })
  for (const viewport of [{ width: 1920, height: 1080 }, { width: 1440, height: 900 }, { width: 393, height: 852 }]) {
    const page = await browser.newPage({ viewport })
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto(fixture.url)
    await page.getByLabel('CPF', { exact: true }).fill(env.DEMO_ADMIN_CPF)
    await page.getByLabel('Senha', { exact: true }).fill(env.DEMO_ADMIN_PASSWORD)
    await page.getByRole('button', { name: 'Entrar', exact: true }).click()
    await page.locator('.admin-home-main').waitFor()
    if (viewport.width < 760) await page.getByRole('button', { name: 'Abrir menu de navega\u00e7\u00e3o', exact: true }).click()
    await page.locator('.sidebar').getByRole('button', { name: 'Ofertas e servi\u00e7os', exact: true }).click()
    assert.equal(await page.locator('.offers-table-row').filter({ hasText: 'Oferta do cliente' }).getByRole('button', { name: 'Recusar', exact: true }).count(), 0)
    await page.getByRole('button', { name: 'Inserir Oferta Manualmente', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'Inserir oferta manualmente' })
    const service = `Oferta manual ${viewport.width}`
    await form.getByLabel('CNPJ/CPF *', { exact: true }).fill('12345678000190')
    await form.getByLabel('Empresa *', { exact: true }).fill('Cliente teste')
    await form.getByLabel('Prazo solicitado *', { exact: true }).fill('2026-12-20')
    await form.getByLabel('Pe\u00e7a/Servi\u00e7o *', { exact: true }).fill(service)
    await form.getByLabel('Quantidade *', { exact: true }).fill('10')
    await form.getByLabel('N\u00famero da etiqueta', { exact: true }).fill('TESTE')
    await form.getByLabel('Descri\u00e7\u00e3o do servi\u00e7o *', { exact: true }).fill('Teste de recusa')
    await form.getByRole('button', { name: 'Adicionar solicita\u00e7\u00e3o', exact: true }).click()
    await form.waitFor({ state: 'detached' })
    const row = page.locator('.offers-table-row').filter({ hasText: service })
    const reject = row.getByRole('button', { name: 'Recusar', exact: true })
    await reject.waitFor()
    const colors = await reject.evaluate((button) => getComputedStyle(button).color.match(/\d+/g).map(Number))
    assert.ok(colors[0] > colors[1] && colors[0] > colors[2], 'Reject command should be red')
    const reviewBox = await row.getByRole('button', { name: 'Em an\u00e1lise', exact: true }).boundingBox()
    const rejectBox = await reject.boundingBox()
    assert.ok(rejectBox.x >= reviewBox.x + reviewBox.width - 1, 'Refusal must sit beside the analysis action')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    await page.screenshot({ path: `test-results/offer-refusal-button-${viewport.width}.png`, fullPage: true })
    await reject.click()
    const modal = page.getByRole('dialog', { name: 'Recusar oferta?' })
    await modal.waitFor()
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Cancelar')
    await modal.getByRole('button', { name: 'Cancelar', exact: true }).click()
    assert.equal(await row.locator('.offer-table-status').innerText(), 'Em an\u00e1lise')
    await reject.click()
    await page.keyboard.press('Escape')
    await modal.waitFor({ state: 'detached' })
    await reject.click()
    await page.route('**/offers/*/reject', (route) => route.fulfill({ status: 409, json: { message: 'Falha de teste' } }))
    await modal.getByRole('button', { name: 'Recusar oferta', exact: true }).click()
    await modal.getByRole('alert').waitFor()
    assert.equal(await row.locator('.offer-table-status').innerText(), 'Em an\u00e1lise')
    await page.unroute('**/offers/*/reject')
    await page.screenshot({ path: `test-results/offer-refusal-modal-${viewport.width}.png` })
    await modal.getByRole('button', { name: 'Recusar oferta', exact: true }).click()
    await modal.waitFor({ state: 'detached' })
    assert.equal(await row.locator('.offer-table-status').innerText(), 'Recusada')
    assert.equal(await row.getByRole('button').count(), 0)
    await page.getByRole('button', { name: /^Recusadas/ }).click()
    assert.equal(await page.locator('.offers-table-row').filter({ hasText: 'Oferta do cliente' }).count(), 0)
    assert.equal(await row.count(), 1)
    await page.reload()
    await row.waitFor()
    assert.equal(await row.locator('.offer-table-status').innerText(), 'Recusada')
    assert.deepEqual(errors, [])
    await page.close()
  }
  console.log('Manual offer refusal passed at 1920, 1440 and iPhone 15: manual insertion, adjacent red action, cancel/Escape, server error, confirmation, rejected filter and reload persistence.')
} finally { await browser.close(); await fixture.close() }
