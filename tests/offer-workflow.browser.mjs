import assert from 'node:assert/strict'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { createWorkflowFixture, offerDraft } from './workflowFixture.js'

const modulePath = process.env.PLAYWRIGHT_MODULE
const { chromium } = await import(modulePath ? pathToFileURL(modulePath).href : 'playwright')
// Accepting the offer takes its material out of the stock: a simulated stock database for that moment.
const inventoryPool = { async getConnection() {
  return {
    async beginTransaction() {}, async commit() {}, async rollback() {}, release() {},
    async execute(sql) {
      if (sql.startsWith('SELECT id FROM inventory_movements')) return [[]]
      if (sql.startsWith('SELECT id, name')) return [[{ id: 1, name: 'Alumínio cadastrado teste', quantity: 15, minimum: 0, unitPrice: 40 }]]
      return [{}]
    },
  }
} }
const fixture = await createWorkflowFixture({ inventoryPool, accountsEnv: { DEMO_ADMIN_CPF: '12345678901', DEMO_ADMIN_PASSWORD: 'teste', DEMO_ADMIN_NAME: 'Gustavo' } })
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1366, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
// On phones the side menu opens from the top button first.
const navigate = async (label) => {
  const opener = page.getByRole('button', { name: 'Abrir menu de navegação', exact: true })
  if (await opener.isVisible() && await opener.getAttribute('aria-expanded') === 'false') await opener.click()
  await page.locator('.sidebar').getByRole('button', { name: label, exact: true }).click()
}
const waitSaved = () => page.waitForFunction(() => !document.querySelector('.offer-proposal-button')?.disabled)

try {
  const created = await fixture.adminRequest('/offers', 'POST', offerDraft)
  const offerId = created.data.item.id
  await page.route('**/api/**', async (route) => {
    const url = new URL(route.request().url())
    const response = await route.fetch({ url: `${fixture.url}${url.pathname}${url.search}` })
    await route.fulfill({ response })
  })
  await page.goto(process.env.PREVIEW_URL || fixture.url)
  await page.getByLabel('CPF', { exact: true }).fill('12345678901')
  await page.getByLabel('Senha', { exact: true }).fill('teste')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await navigate('Máquinas')
  // The sector is only marked, from Cadastros > Setores.
  await fixture.adminRequest('/sectors', 'POST', { name: 'Usinagem' })
  await page.getByRole('button', { name: 'Adicionar máquina', exact: true }).click()
  const machineDialog = page.getByRole('dialog')
  await machineDialog.getByLabel('Nome da máquina').fill('Torno cadastrado teste')
  await machineDialog.getByLabel('Tipo', { exact: true }).fill('Torno')
  await machineDialog.getByRole('button', { name: 'Usinagem', exact: true }).click()
  await machineDialog.getByLabel('Valor da hora (R$)').fill('145')
  await machineDialog.getByRole('button', { name: 'Salvar máquina' }).click()
  await navigate('Estoque')
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  const inventoryDialog = page.getByRole('dialog')
  await inventoryDialog.getByLabel('Nome do material').fill('Alumínio cadastrado teste')
  await inventoryDialog.getByLabel('Especificação', { exact: true }).fill('Chapa 10 mm')
  await inventoryDialog.getByLabel('Quantidade disponível').fill('15')
  await inventoryDialog.getByLabel('Valor por kg').fill('40')
  await inventoryDialog.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  // The purchase is offered to the financial module; here it is left for later.
  await page.getByRole('dialog', { name: 'Lançar esta compra no financeiro?', exact: true }).getByRole('button', { name: 'Não lançar agora', exact: true }).click()
  await navigate('Ofertas e serviços')
  await page.locator('.offer-review-button').click()
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  const materialForm = page.locator('.offer-inline-form').first()
  await materialForm.getByRole('combobox', { name: /^Material/ }).fill('Alu')
  await page.getByRole('option', { name: /Alumínio cadastrado teste/ }).waitFor({ state: 'visible' })
  await page.getByRole('option', { name: /Alumínio cadastrado teste/ }).click()
  assert.equal(await materialForm.getByLabel('Especificação').inputValue(), 'Chapa 10 mm')
  assert.equal(await materialForm.getByLabel('Valor unitário').inputValue(), '40')
  await materialForm.getByLabel('Quantidade (kg)').fill('5')
  await materialForm.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await waitSaved()
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await materialForm.getByRole('combobox', { name: /^Material/ }).fill('Titanio novo teste')
  await materialForm.getByLabel('Quantidade (kg)').fill('12.5')
  await materialForm.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await waitSaved()
  const badge = page.locator('.material-stock-status--unknown')
  assert.equal(await badge.innerText(), 'Não verificado')
  assert.equal(await badge.evaluate((element) => getComputedStyle(element).color), 'rgb(196, 43, 59)')
  // The missing material is requested only when the offer is accepted: while it is analysed, Pedidos de material stays empty.
  await navigate('Pedidos de material')
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  const requestRow = page.locator('.material-orders-table tbody tr').filter({ hasText: 'Titanio novo teste' })
  assert.equal(await requestRow.count(), 0)
  await navigate('Ofertas e serviços')
  await page.locator('.offer-review-button').click()
  await page.getByRole('button', { name: 'Adicionar mão de obra', exact: true }).click()
  const laborForm = page.locator('.offer-labor-form')
  const machineSelect = laborForm.locator('select').nth(1)
  const machineId = await machineSelect.locator('option').filter({ hasText: 'Torno cadastrado teste' }).getAttribute('value')
  await machineSelect.selectOption(machineId)
  assert.equal(await laborForm.getByLabel('Valor da hora').inputValue(), '145')
  await laborForm.getByLabel('Valor da hora').fill('175')
  await laborForm.getByLabel('Tempo (horas)').fill('2')
  await page.screenshot({ path: 'test-results/offer-machine-desktop.png', fullPage: true })
  await laborForm.getByRole('button', { name: 'Adicionar mão de obra', exact: true }).click()
  await waitSaved()
  await page.getByRole('checkbox', { name: 'Tornearia', exact: true }).check()
  await waitSaved()
  await page.getByRole('checkbox', { name: 'Pintura', exact: true }).check()
  await waitSaved()
  await page.getByRole('radio', { name: 'Produto', exact: true }).check()
  await waitSaved()
  await page.screenshot({ path: 'test-results/offer-details-desktop.png', fullPage: true })
  await navigate('Pedidos de material')
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  const row = page.locator('.material-orders-table tbody tr')
  assert.equal(await row.count(), 0, 'still nothing requested before the acceptance')
  await navigate('Ofertas e serviços')
  await page.locator('.offer-review-button').click()
  assert.equal(await page.getByRole('checkbox', { name: 'Pintura', exact: true }).isChecked(), true)
  assert.equal(await page.getByRole('radio', { name: 'Produto', exact: true }).isChecked(), true)
  await page.getByRole('button', { name: 'Fazer proposta', exact: true }).click()
  await page.getByRole('heading', { name: 'Fazer proposta', exact: true }).waitFor()
  assert.equal(await page.locator('.proposal-choice-row').count(), 0)
  const proposalCards = page.locator('.proposal-card')
  const margins = () => proposalCards.locator('.proposal-card-column > div').filter({ has: page.getByRole('button', { name: 'Editar margin', exact: true }) }).locator('strong').allTextContents()
  assert.deepEqual(await margins(), ['15,0%', '20,0%', '25,0%', '30,0%'])
  await proposalCards.first().getByRole('button', { name: 'Editar margin', exact: true }).click()
  await proposalCards.first().locator('.proposal-inline-edit').fill('17')
  await proposalCards.first().locator('.proposal-inline-edit').press('Tab')
  assert.deepEqual(await margins(), ['17,0%', '20,0%', '25,0%', '30,0%'])
  await page.screenshot({ path: 'test-results/proposal-margins-desktop.png', fullPage: true })
  const proposalResponse = page.waitForResponse((response) => response.url().endsWith(`/offers/${offerId}/proposal-document`) && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Gerar proposta em PDF', exact: true }).click()
  await page.getByRole('button', { name: /^Etiqueta/ }).click()
  await page.getByLabel('Horas de Serv Usinagem em Torno Convencional', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Gerar PDF', exact: true }).click()
  assert.equal((await proposalResponse).status(), 200)
  // A price list (Etiqueta) states its own price: the proposal keeps the real margin of the document on the cost.
  const savedProposal = (await fixture.adminRequest('/offers', 'GET', undefined, fixture.admin)).data.items.find((item) => item.id === offerId).proposal
  assert.equal(savedProposal.margin, Math.round((savedProposal.osValue - savedProposal.serviceValue) / savedProposal.serviceValue * 1000) / 10)
  await page.getByRole('tab', { name: 'Detalhes da oferta', exact: true }).click()
  await page.getByRole('button', { name: 'Fazer proposta', exact: true }).click()
  await page.getByRole('heading', { name: 'Fazer proposta', exact: true }).waitFor()
  assert.equal((await margins())[0], `${savedProposal.margin.toFixed(1).replace('.', ',')}%`, 'the saved option shows its margin')
  await page.getByRole('button', { name: 'Aceitar Oferta', exact: true }).click()
  await page.getByRole('dialog', { name: 'Tem certeza que deseja aceitar a oferta?' }).getByRole('button', { name: 'Sim, aceitar e gerar a OS', exact: true }).click()
  await page.locator('.order-detail-card').waitFor()
  // Accepted: the request appears with the OS, is shared with other computers and survives a reload.
  await navigate('Pedidos de material')
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  assert.equal(await row.count(), 1)
  assert.match(await row.innerText(), /Titanio novo teste.*12,5 kg/s)
  assert.match(await row.innerText(), /OS-/)
  const otherContext = await browser.newContext({ viewport: { width: 1366, height: 900 } })
  const otherPage = await otherContext.newPage()
  await otherPage.goto(fixture.url)
  await otherPage.getByLabel('CPF', { exact: true }).fill('12345678901')
  await otherPage.getByLabel('Senha', { exact: true }).fill('teste')
  await otherPage.getByRole('button', { name: 'Entrar', exact: true }).click()
  await otherPage.locator('.sidebar').getByRole('button', { name: 'Pedidos de material', exact: true }).click()
  await otherPage.locator('.material-orders-table tbody tr').filter({ hasText: 'Titanio novo teste' }).waitFor()
  await otherContext.close()
  await page.reload()
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  await navigate('Pedidos de material')
  assert.equal(await requestRow.count(), 1)
  await page.screenshot({ path: 'test-results/material-orders-desktop.png', fullPage: true })
  await row.getByRole('button', { name: /^OS-/ }).click()
  await page.locator('.order-detail-card').waitFor()
  const orderText = await page.locator('.order-detail-card').innerText()
  assert.equal(await page.locator('.os-planning-facts > div').filter({ has: page.locator('dt', { hasText: /^Tipo$/ }) }).locator('dd').innerText(), 'Produto')
  assert.deepEqual(await page.locator('.os-proposal-stages li').allTextContents(), ['1Tornearia', '2Pintura'])
  assert.match(orderText, /350,00/)
  assert.equal((await fixture.request('/orders', 'GET', undefined, fixture.admin)).data.items[0].resources.laborEntries[0].hourlyRate, 175)
  await page.setViewportSize({ width: 390, height: 844 })
  await navigate('Pedidos de material')
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  await page.screenshot({ path: 'test-results/material-orders-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await row.getByRole('button', { name: /^OS-/ }).click()
  await page.screenshot({ path: 'test-results/order-details-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await page.getByRole('tab', { name: 'Detalhes da oferta', exact: true }).click()
  await page.screenshot({ path: 'test-results/offer-details-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await page.setViewportSize({ width: 320, height: 740 })
  await page.screenshot({ path: 'test-results/offer-details-mobile-small.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await navigate('Pedidos de material')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await page.setViewportSize({ width: 1366, height: 900 })
  await navigate('Estoque')
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await inventoryDialog.getByLabel('Nome do material').fill('Titanio novo teste')
  await inventoryDialog.getByLabel('Quantidade disponível').fill('12.5')
  await inventoryDialog.getByLabel('Valor por kg').fill('20')
  await inventoryDialog.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  // Adding the stock offers to post the purchase in the finance; it is left for later here.
  await page.getByRole('dialog', { name: 'Lançar esta compra no financeiro?', exact: true }).getByRole('button', { name: 'Não lançar agora', exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('Browser workflow passed: missing material requested on acceptance and shared between computers, inventory suggestions, machine rate, process settings, PDF, material request/OS links, desktop/mobile.')
} catch (error) {
  await page.screenshot({ path: 'test-results/workflow-failure.png', fullPage: true })
  throw error
} finally {
  await page.unrouteAll({ behavior: 'ignoreErrors' })
  await context.close()
  await browser.close()
  await fixture.close()
}
