  const created = await fixture.request('/offers', 'POST', offerDraft)
  const offerId = created.data.item.id
  await page.route('**/api/**', async (route) => {
    const url = new URL(route.request().url())
    const response = await route.fetch({ url: `${fixture.url}${url.pathname}${url.search}` })
    await route.fulfill({ response })
  })
  await page.goto(process.env.PREVIEW_URL || fixture.url)
  await page.getByLabel('CPF', { exact: true }).fill('12345678901')
  await page.getByLabel('Senha', { exact: true }).fill('teste')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await navigate('Máquinas')
  await page.getByRole('button', { name: 'Adicionar máquina', exact: true }).click()
  const machineDialog = page.getByRole('dialog')
  await machineDialog.getByLabel('Nome da máquina').fill('Torno cadastrado teste')
  await machineDialog.getByLabel('Tipo', { exact: true }).fill('Torno')
  await machineDialog.getByLabel('Setor').fill('Usinagem')
  await machineDialog.getByLabel('Valor da hora (R$)').fill('145')
  await machineDialog.getByRole('button', { name: 'Salvar máquina' }).click()
  await navigate('Estoque')
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  const inventoryDialog = page.getByRole('dialog')
  await inventoryDialog.getByLabel('Nome do material').fill('Alumínio cadastrado teste')
  await inventoryDialog.getByLabel('Especificação', { exact: true }).fill('Chapa 10 mm')
  await inventoryDialog.getByLabel('Quantidade disponível').fill('15')
  await inventoryDialog.getByLabel('Valor por kg').fill('40')
  await inventoryDialog.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await navigate('Ofertas e serviços')
  await page.locator('.offer-review-button').click()
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  const materialForm = page.locator('.offer-inline-form').first()
  await materialForm.getByRole('combobox').fill('Alu')
  await page.getByRole('option', { name: /Alumínio cadastrado teste/ }).waitFor({ state: 'visible' })
  await page.getByRole('option', { name: /Alumínio cadastrado teste/ }).click()
  assert.equal(await materialForm.getByLabel('Especificação').inputValue(), 'Chapa 10 mm')
  assert.equal(await materialForm.getByLabel('Valor unitário').inputValue(), '40')
  await materialForm.getByLabel('Quantidade (kg)').fill('5')
  await materialForm.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await waitSaved()
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await materialForm.getByRole('combobox').fill('Titanio novo teste')
  await materialForm.getByLabel('Quantidade (kg)').fill('12.5')
  await materialForm.getByRole('button', { name: 'Adicionar material', exact: true }).click()
  await waitSaved()
  const badge = page.locator('.material-stock-status--unknown')
  assert.equal(await badge.innerText(), 'Não verificado')
  assert.equal(await badge.evaluate((element) => getComputedStyle(element).color), 'rgb(196, 43, 59)')
  await navigate('Pedidos')
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  assert.equal(await page.locator('.material-orders-table tbody tr').count(), 0)
  await navigate('Estoque')
  const pendingSection = page.locator('.pending-material-card')
  const pendingRow = pendingSection.locator('.pending-material-row:not(.pending-material-row--header)')
  assert.equal(await pendingRow.count(), 1)
  assert.match(await pendingRow.innerText(), /Titanio novo teste.*12,5 kg.*OF-/s)
  await pendingRow.getByRole('button', { name: 'Abrir solicitação de compra' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click()
  await navigate('Pedidos')
  assert.equal(await page.locator('.material-orders-table tbody tr').count(), 0)
  await page.reload()
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  await navigate('Pedidos')
  assert.equal(await page.locator('.material-orders-table tbody tr').count(), 0)
  await navigate('Estoque')
  await pendingRow.getByRole('button', { name: 'Abrir solicitação de compra' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirmar solicitação' }).click()
  await pendingRow.getByText('Compra solicitada', { exact: true }).waitFor()
  assert.match(await pendingRow.innerText(), /Compra solicitada/)
  await navigate('Pedidos')
  assert.equal(await page.locator('.material-orders-table tbody tr').count(), 1)
  const otherContext = await browser.newContext({ viewport: { width: 1366, height: 900 } })
  const otherPage = await otherContext.newPage()
  await otherPage.goto(fixture.url)
  await otherPage.getByLabel('CPF', { exact: true }).fill('12345678901')
  await otherPage.getByLabel('Senha', { exact: true }).fill('teste')
  await otherPage.getByRole('button', { name: 'Entrar', exact: true }).click()
  await otherPage.locator('.sidebar').getByRole('button', { name: 'Pedidos', exact: true }).click()
  await otherPage.locator('.material-orders-table tbody tr').filter({ hasText: 'Titanio novo teste' }).waitFor()
  await otherContext.close()
  await page.reload()
  await page.getByRole('heading', { name: 'Pedidos de material' }).waitFor()
  await navigate('Pedidos')
  assert.equal(await page.locator('.material-orders-table tbody tr').count(), 1)
  await navigate('Estoque')
  await page.screenshot({ path: 'test-results/inventory-pending-offer-desktop.png', fullPage: true })
  await pendingRow.getByRole('button', { name: /^OF-/ }).click()
  await page.getByRole('button', { name: 'Adicionar mão de obra', exact: true }).click()
  const laborForm = page.locator('.offer-labor-form')
  const machineSelect = laborForm.locator('select').nth(1)
  const machineId = await machineSelect.locator('option').filter({ hasText: 'Torno cadastrado teste' }).getAttribute('value')
  await machineSelect.selectOption(machineId)
  assert.equal(await laborForm.getByLabel('Valor da hora').inputValue(), '145')
  await laborForm.getByLabel('Valor da hora').fill('175')
  await laborForm.getByLabel('Tempo (horas)').fill('2')
  await page.screenshot({ path: 'test-results/offer-machine-desktop.png', fullPage: true })
  await laborForm.getByRole('button', { name: 'Adicionar mão de obra', exact: true }).click()
  await waitSaved()
  await page.getByRole('checkbox', { name: 'Tornearia', exact: true }).check()
  await waitSaved()
  await page.getByRole('checkbox', { name: 'Pintura', exact: true }).check()
  await waitSaved()
  await page.getByRole('radio', { name: 'Produto', exact: true }).check()
  await waitSaved()
  await page.screenshot({ path: 'test-results/offer-details-desktop.png', fullPage: true })
