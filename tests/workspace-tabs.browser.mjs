import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createWorkflowFixture } from './workflowFixture.js'

const fixture = await createWorkflowFixture({ accountsEnv: { DEMO_ADMIN_CPF: '12345678901', DEMO_ADMIN_PASSWORD: 'test-tabs', DEMO_ADMIN_NAME: 'Gustavo' } })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
const navigate = async (name) => {
  const opener = page.getByRole('button', { name: 'Abrir menu de navegação', exact: true })
  if (await opener.isVisible() && await opener.getAttribute('aria-expanded') === 'false') await opener.click()
  const item = page.locator('.sidebar').getByRole('button', { name, exact: true })
  // Registrations and finance live in groups of the side menu that start closed.
  for (const group of ['Cadastros', 'Operação', 'Gestão Financeira']) if (!await item.isVisible() && await page.locator('.sidebar').getByRole('button', { name: group, exact: true }).count()) await page.locator('.sidebar').getByRole('button', { name: group, exact: true }).click()
  await item.click()
}
const left = page.getByRole('button', { name: 'Rolar abas para a esquerda', exact: true })
const right = page.getByRole('button', { name: 'Rolar abas para a direita', exact: true })
const closeAll = page.getByRole('button', { name: 'Fechar todas as abas', exact: true })
const arrows = (visible) => page.waitForFunction((visible) => document.querySelectorAll('.workspace-tabs-control:not(.workspace-tabs-close-all)').length === (visible ? 2 : 0), visible)
const scrollPosition = () => page.locator('.workspace-tabs-list').evaluate((element) => element.scrollLeft)

try {
  await page.goto(fixture.url)
  await page.getByLabel('CPF', { exact: true }).fill('12345678901')
  await page.getByLabel('Senha', { exact: true }).fill('test-tabs')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await page.getByRole('heading', { name: 'Bem-vindo, Gustavo', exact: true }).waitFor()
  assert.equal(await closeAll.count(), 0)
  await arrows(false)
  await navigate('M\u00e1quinas')
  await navigate('Estoque')
  assert.equal(await page.getByRole('tab').count(), 3)
  assert.equal(await closeAll.count(), 0)
  await navigate('Funcion\u00e1rios')
  await closeAll.waitFor()
  assert.equal(await page.getByRole('tab').count(), 4)
  await arrows(false)
  for (const name of ['Calculadora de pesos e medidas', 'Servi\u00e7os em andamento', 'Ofertas e servi\u00e7os', 'Administradores', 'Clientes', 'Pedidos de material']) await navigate(name)
  await arrows(true)
  const selectedVisible = await page.locator('.workspace-tabs-list').evaluate((list) => {
    const viewport = list.getBoundingClientRect(), selected = list.querySelector('.workspace-tab--active').getBoundingClientRect()
    return selected.left >= viewport.left - 1 && selected.right <= viewport.right + 1
  })
  assert.ok(selectedVisible, 'The newly selected tab is visible')
  await navigate('In\u00edcio')
  await arrows(true)
  assert.equal(await left.isDisabled(), true)
  assert.equal(await right.isEnabled(), true)
  const clock = await page.locator('.workspace-tabs-clock').boundingBox()
  await right.click()
  assert.ok(await scrollPosition() > 0)
  assert.equal(await left.isEnabled(), true)
  while (await right.isEnabled()) await right.click()
  assert.equal(await right.isDisabled(), true)
  const end = await scrollPosition()
  await left.click()
  assert.ok(await scrollPosition() < end)
  assert.deepEqual(await page.locator('.workspace-tabs-clock').boundingBox(), clock)
  const listBox = await page.locator('.workspace-tabs-list').boundingBox()
  const leftBox = await left.boundingBox(), rightBox = await right.boundingBox(), closeBox = await closeAll.boundingBox()
  const bellBox = await page.locator('.notifications-trigger').boundingBox()
  assert.ok(leftBox.x + leftBox.width <= listBox.x + 1)
  assert.ok(listBox.x + listBox.width <= rightBox.x + 1)
  assert.ok(rightBox.x + rightBox.width <= closeBox.x + 1)
  assert.ok(closeBox.x + closeBox.width <= bellBox.x + 1)
  await page.screenshot({ path: 'test-results/workspace-tabs-overflow.png' })

  await page.setViewportSize({ width: 2800, height: 768 })
  await arrows(false)
  const fittingWidth = await page.locator('.workspace-tabs-list').evaluate((list) => {
    const first = list.firstElementChild.getBoundingClientRect(), last = list.lastElementChild.getBoundingClientRect()
    return Math.ceil(innerWidth - list.clientWidth + last.right - first.left + 2)
  })
  await page.setViewportSize({ width: fittingWidth, height: 768 })
  await arrows(false)
  await closeAll.waitFor()
  await page.setViewportSize({ width: fittingWidth - 16, height: 768 })
  await arrows(true)
  await page.getByRole('button', { name: 'Recolher menu lateral', exact: true }).click()
  await arrows(false)
  await page.getByRole('button', { name: 'Expandir menu lateral', exact: true }).click()
  await arrows(true)
  await page.setViewportSize({ width: 2800, height: 768 })
  await arrows(false)
  await page.screenshot({ path: 'test-results/workspace-tabs-fitting.png' })

  const machineTab = page.getByRole('tab', { name: 'M\u00e1quinas', exact: true }).locator('..')
  const dashboardTab = page.getByRole('tab', { name: 'In\u00edcio', exact: true }).locator('..')
  await machineTab.dragTo(dashboardTab)
  assert.deepEqual((await page.getByRole('tab').allTextContents()).slice(0, 2), ['M\u00e1quinas', 'In\u00edcio'])
  while (await page.getByRole('tab').count() > 3) await page.locator('.workspace-tab-close').last().click()
  assert.equal(await closeAll.count(), 0)
  await page.setViewportSize({ width: 390, height: 844 })
  await arrows(false)
  assert.equal(await closeAll.count(), 0)
  await page.screenshot({ path: 'test-results/workspace-tabs-three-mobile.png' })
  await navigate('Relat\u00f3rios')
  await closeAll.waitFor()
  await arrows(true)
  await page.getByRole('tab', { name: 'In\u00edcio', exact: true }).click()
  assert.equal(await page.locator('.workspace-tabs-clock').isVisible(), false)
  const mobileBell = await page.locator('.notifications-trigger').boundingBox()
  assert.ok(mobileBell.x + mobileBell.width <= 391)
  await page.screenshot({ path: 'test-results/workspace-tabs-mobile.png' })
  await closeAll.press('Enter')
  await page.getByRole('heading', { name: 'Bem-vindo, Gustavo', exact: true }).waitFor()
  assert.deepEqual(await page.getByRole('tab').allTextContents(), ['In\u00edcio'])
  assert.equal(await closeAll.count(), 0)
  await arrows(false)
  await page.reload()
  await page.getByRole('heading', { name: 'Bem-vindo, Gustavo', exact: true }).waitFor()
  assert.deepEqual(await page.getByRole('tab').allTextContents(), ['In\u00edcio'])
  assert.equal(await page.getByLabel('CPF', { exact: true }).count(), 0)
  const workspace = await page.evaluate(() => JSON.parse(sessionStorage.getItem('gmac-admin-workspace')))
  assert.equal(workspace.offerId, null)
  assert.equal(workspace.orderCode, null)
  assert.deepEqual(errors, [])
  console.log('Workspace tabs passed: overflow-only arrows, bidirectional scrolling, fixed clock/bell, close-all threshold, resize/sidebar, reordering, mobile and session restoration.')
} catch (error) {
  await page.screenshot({ path: 'test-results/workspace-tabs-failure.png' })
  throw error
} finally {
  await browser.close()
  await fixture.close()
}
