import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { createWorkflowFixture, offerDraft } from './workflowFixture.js'

const fixture = await createWorkflowFixture()
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 1366, height: 900 } })
const page = await context.newPage()
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
try {
  await fixture.mutateStore((store) => { store.machines = [{ id: 'torno', name: 'Torno 01' }, { id: 'fresa', name: 'Fresa 02' }] })
  const employee = (await fixture.request('/employees', 'POST', { name: 'Ana Teste', birthDate: '1990-01-01', cpf: '00000000001', email: 'ana@example.invalid', identification: '001' })).data.item
  const offer = (await fixture.request('/offers', 'POST', offerDraft)).data.item
  await fixture.request(`/offers/${offer.id}/resources`, 'PUT', { materials: [], laborEntries: [], kind: 'service', stages: ['turning'] })
  await fixture.request(`/offers/${offer.id}/proposal`, 'POST', { layout: 'classic', proposal: { key: 'A', deadline: offerDraft.deadline, serviceValue: 100 } })
  const order = (await fixture.request(`/offers/${offer.id}/accept`, 'POST')).data.item
  await context.addInitScript((token) => sessionStorage.setItem('gmac-operator-token', token), fixture.operatorToken)
  await page.goto(fixture.url)
  assert.equal(await page.getByRole('button', { name: 'Troca de máquina ou serviço', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Trabalhar neste projeto', exact: true }).click()
  await page.getByLabel('Funcionário', { exact: true }).selectOption(String(employee.id))
  assert.equal(await page.getByRole('button', { name: 'Iniciar trabalho', exact: true }).isEnabled(), false, 'a machine or a labor service must be chosen')
  await page.getByRole('radio', { name: 'Serviço de hora homem', exact: true }).check()
  assert.equal(await page.getByRole('combobox', { name: 'Máquina', exact: true }).count(), 0)
  await page.getByRole('radio', { name: 'Máquina', exact: true }).check()
  assert.equal(await page.getByRole('combobox', { name: 'Serviço de hora homem', exact: true }).count(), 0, 'machine and labor service cannot be selected together')
  await page.getByRole('combobox', { name: 'Máquina', exact: true }).selectOption('torno')
  await page.getByRole('button', { name: 'Iniciar trabalho', exact: true }).click()
  const swap = page.getByRole('button', { name: 'Troca de máquina ou serviço', exact: true })
  await swap.waitFor()
  assert.match(await page.locator('.operator-workers').innerText(), /Ana Teste[\s\S]*Máquina: Torno 01/)
  const before = (await fixture.request('/operations/orders')).data.items[0].operation
  const session = await page.evaluate((code) => sessionStorage.getItem(`gmac-operator-sessions-${code}`), order.code)
  assert.ok(JSON.parse(session)[before.activeSessions[0].id])
  const quantities = page.locator('.operator-stage-action input')
  await quantities.first().fill('2')
  await swap.click()
  const dialog = page.getByRole('dialog')
  await dialog.waitFor()
  assert.match(await dialog.innerText(), /Recurso atual: Máquina: Torno 01/)
  assert.equal(await page.getByLabel('Nova máquina', { exact: true }).inputValue(), 'torno')
  assert.equal(await page.getByRole('button', { name: 'Confirmar troca', exact: true }).isEnabled(), false)
  await page.screenshot({ path: 'test-results/operator-machine-change-desktop.png' })
  await page.getByLabel('Nova máquina', { exact: true }).selectOption('fresa')
  await page.getByRole('button', { name: 'Confirmar troca', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const after = (await fixture.request('/operations/orders')).data.items[0].operation
  assert.equal(after.activeSessions[0].machineId, 'fresa')
  assert.equal(after.activeSessions[0].id, before.activeSessions[0].id)
  assert.equal(after.activeSessions[0].startedAt, before.activeSessions[0].startedAt)
  assert.equal(await quantities.first().inputValue(), '2')
  assert.equal(await page.evaluate((code) => sessionStorage.getItem(`gmac-operator-sessions-${code}`), order.code), session)
  await page.locator('.operator-history summary').click()
  await page.getByText('Trocou de máquina', { exact: true }).waitFor()
  assert.match(await page.locator('.operator-history').innerText(), /Torno 01 → Máquina Fresa 02/)
  await page.reload()
  const worker = page.locator('.operator-worker-toggle').filter({ hasText: 'Ana Teste' })
  await worker.waitFor()
  assert.equal(await swap.count(), 0, 'actions appear after clicking the employee name')
  await worker.click()
  await swap.waitFor()
  await page.getByRole('button', { name: 'Visualizar informações do projeto', exact: true }).click()
  await page.locator('.operator-project-info').waitFor()
  assert.match(await page.locator('.operator-project-info').innerText(), /Máquina atual\s*Fresa 02/)
  await page.getByRole('button', { name: /Voltar/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await worker.waitFor()
  if (!await swap.count()) await worker.click()
  await swap.click()
  await dialog.waitFor()
  await page.screenshot({ path: 'test-results/operator-machine-change-mobile.png' })
  const bounds = await dialog.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
  // Leaves the machine for manual work with a labor service.
  await dialog.getByRole('radio', { name: 'Serviço de hora homem', exact: true }).check()
  const service = page.getByLabel('Novo serviço', { exact: true })
  assert.equal(await service.inputValue(), '')
  const serviceId = await service.locator('option').nth(1).getAttribute('value')
  await service.selectOption(serviceId)
  await page.getByRole('button', { name: 'Confirmar troca', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const manual = (await fixture.request('/operations/orders')).data.items[0].operation.activeSessions[0]
  assert.equal(manual.machineId, null)
  assert.equal(String(manual.laborServiceId), serviceId)
  // And back from the labor service to a machine.
  await page.getByRole('button', { name: 'Troca de máquina ou serviço', exact: true }).click()
  await dialog.waitFor()
  assert.equal(await dialog.getByRole('radio', { name: 'Serviço de hora homem', exact: true }).isChecked(), true)
  await dialog.getByRole('radio', { name: 'Máquina', exact: true }).check()
  await page.getByLabel('Nova máquina', { exact: true }).selectOption('torno')
  await page.getByRole('button', { name: 'Confirmar troca', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  const back = (await fixture.request('/operations/orders')).data.items[0].operation.activeSessions[0]
  assert.deepEqual([back.machineId, back.laborServiceId], ['torno', null])
  await page.getByRole('button', { name: 'Pausar trabalho', exact: true }).click()
  await dialog.locator('select').selectOption('Descanso')
  await page.getByRole('button', { name: 'Confirmar pausa', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  assert.equal(await swap.count(), 0)
  assert.equal((await fixture.request('/operations/orders')).data.items[0].operation.status, 'paused')
  assert.deepEqual(errors, [])
  console.log('Operator machine change passed: exclusive machine/service choice, actions under the employee name, same work session, reload, machine and labor service swaps, history, pause and desktop/mobile layout.')
} catch (error) {
  await page.screenshot({ path: 'test-results/operator-machine-change-failure.png' })
  throw error
} finally {
  await browser.close()
  await fixture.close()
}
